"""The one file Media Keys writes outside its own directory: a hotkeygen override.

Batocera's ``hotkeygen`` stays the only reader of the keyboard (a second reader
that did not grab the device would double-handle every press). The Drone adds
``drone-media-keys.conf`` to the *user* hotkeygen config directory, mapping each
managed key to ``<launcher> <binding-id>``; stock files under ``/etc/hotkeygen``
are never read-modified or written. Disabling or removing the integration
deletes just that file (and only if it still carries the Drone marker), which
restores the stock behaviour.

Press-time lookup happens in the dispatcher, so editing a binding or script
never rewrites this file -- only enabling/repairing does.

NOTE: the line syntax and merge-vs-replace behaviour of the user directory
have to be confirmed on a real device (issue #152 open items); both are
confined to ``OVERRIDE_FILE_NAME``/``render_override`` so adjusting them is a
one-place change.
"""

import os
import re
from pathlib import Path
from typing import Callable, List, Optional

from .config import MANAGED_KEYS
from .paths import MediaKeysPaths

try:
    from ..shared.files import atomic_write_bytes
except ImportError:  # pragma: no cover - flat execution
    from integrations.shared.files import atomic_write_bytes  # type: ignore


STOCK_DIR = Path("/etc/hotkeygen")
USER_DIR = Path("/userdata/system/configs/hotkeygen")
OVERRIDE_FILE_NAME = "drone-media-keys.conf"
MARKER = "# Managed by Batocera Drone (Media Keys integration). Delete via Admin > Integrations."
# The command ends up on one config line: refuse anything that could add
# fields, comments, or a second line.
_SAFE_COMMAND_PATH = re.compile(r"^/[A-Za-z0-9._/+-]+$")


def render_override(launcher: Path) -> str:
    command = str(launcher)
    if not _SAFE_COMMAND_PATH.fullmatch(command):
        raise ValueError(f"launcher path is not safe to write into hotkeygen config: {command}")
    lines = [MARKER]
    for binding_id, (key_name, _label) in MANAGED_KEYS.items():
        lines.append(f"{key_name} = {command} {binding_id}")
    return "\n".join(lines) + "\n"


def render_launcher(install_root: Path) -> str:
    root = str(install_root)
    if not _SAFE_COMMAND_PATH.fullmatch(root):
        raise ValueError(f"install path is not safe for the launcher: {root}")
    return (
        "#!/bin/sh\n"
        "# Generated by the Batocera Drone Media Keys integration. Do not edit.\n"
        "# Runs detached so a slow action never blocks hotkeygen; the dispatcher reads\n"
        "# its bindings from disk and does not need the Drone web service to be up.\n"
        f"PYTHONPATH='{root}' nohup python3 -m app.integrations.media_keys.dispatch \"$@\" "
        ">/dev/null 2>&1 &\n"
        "exit 0\n"
    )


class HotkeygenOverrides:
    def __init__(self, paths: MediaKeysPaths, *, user_dir: Optional[Path] = None, stock_dir: Optional[Path] = None,
                 install_root: Optional[Path] = None, proc_root: Path = Path("/proc")) -> None:
        self.paths = paths
        # Resolved at call time so tests (and a future override) can repoint the module constants.
        self.user_dir = Path(user_dir if user_dir is not None else USER_DIR)
        self.stock_dir = Path(stock_dir if stock_dir is not None else STOCK_DIR)
        self.install_root = install_root
        self.proc_root = Path(proc_root)

    @property
    def override_path(self) -> Path:
        return self.user_dir / OVERRIDE_FILE_NAME

    def _install_root(self) -> Path:
        if self.install_root is not None:
            return Path(self.install_root)
        # <install root>/integrations/media-keys
        return self.paths.root.parent.parent

    def expected(self) -> str:
        return render_override(self.paths.launcher)

    def is_ours(self) -> bool:
        path = self.override_path
        try:
            if path.is_symlink() or not path.is_file():
                return False
            return path.read_text(encoding="utf-8").startswith(MARKER)
        except OSError:
            return False

    def applied(self) -> bool:
        if not self.is_ours():
            return False
        try:
            return self.override_path.read_text(encoding="utf-8") == self.expected()
        except OSError:
            return False

    def apply(self) -> dict:
        """Write the launcher and the override. Idempotent."""
        self.paths.ensure(self.paths.bin_dir)
        launcher = self.paths.assert_owned(self.paths.launcher)
        atomic_write_bytes(launcher, render_launcher(self._install_root()).encode("utf-8"), mode=0o755)
        if self.user_dir.is_symlink():
            raise ValueError("the hotkeygen user directory must not be a symbolic link")
        if self.override_path.exists() and not self.is_ours():
            raise ValueError(f"{self.override_path} exists and is not managed by the Drone; refusing to overwrite it")
        changed = not self.applied()
        if changed:
            self.user_dir.mkdir(parents=True, exist_ok=True)
            atomic_write_bytes(self.override_path, self.expected().encode("utf-8"), mode=0o644)
        return {"changed": changed, "path": str(self.override_path)}

    def restore(self) -> dict:
        """Remove only the override this integration wrote (stock behaviour returns)."""
        removed = False
        if self.is_ours():
            self.override_path.unlink()
            removed = True
        return {"removed": removed, "path": str(self.override_path)}

    def hotkeygen_running(self) -> bool:
        try:
            entries = [entry for entry in self.proc_root.iterdir() if entry.name.isdigit()]
        except OSError:
            return False
        for entry in entries:
            try:
                text = (entry / "cmdline").read_bytes().replace(b"\0", b" ").decode("utf-8", "replace")
            except OSError:
                continue
            if "hotkeygen" in text and "media_keys" not in text:
                return True
        return False


def detect_keyboards(devices_file: Path = Path("/proc/bus/input/devices")) -> List[dict]:
    """Input devices that can report the managed media keys (Consumer/System Control, keyboards)."""
    try:
        text = devices_file.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    found = []
    for block in text.split("\n\n"):
        name = ""
        handlers = ""
        for line in block.splitlines():
            if line.startswith("N: Name="):
                name = line.split("=", 1)[1].strip().strip('"')
            elif line.startswith("H: Handlers="):
                handlers = line.split("=", 1)[1].strip()
        events = re.findall(r"event\d+", handlers)
        lowered = name.lower()
        if events and ("kbd" in handlers.split() or "consumer control" in lowered or "system control" in lowered):
            found.append({"name": name[:80], "event": events[0]})
    return found
