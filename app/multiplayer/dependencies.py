"""Optional multiplayer dependencies Drone can install for you (currently: Sunshine).

Sunshine is the host half of remote streaming. Batocera does not ship it, so
this module installs the project's own release for the machine's architecture
into a Drone-owned directory and registers one Batocera service for it:

* nothing outside ``<userdata>/system/drone-multiplayer/sunshine`` and the single
  ``DRONE_SUNSHINE`` service file is created, so removal is complete and safe;
* the download comes only from ``LizardByte/Sunshine`` GitHub releases over HTTPS,
  and the file must match the SHA-256 digest GitHub's release API publishes;
* the AppImage is *extracted* (no FUSE needed, nothing is mounted) and never run
  from the download location;
* every subprocess is a fixed ``argv`` list, ``shell=False``, with a short timeout.

Sunshine keeps its own credentials and client pairings (in ``<userdata>/system/.config/sunshine``);
uninstalling leaves them alone so a reinstall does not lose pairings.
"""

import hashlib
import hmac
import json
import os
import platform
import re
import shlex
import shutil
import ssl
import stat
import subprocess
import tempfile
import threading
import time
import urllib.request
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

from . import models as m

RELEASE_API = "https://api.github.com/repos/LizardByte/Sunshine/releases/latest"
DOWNLOAD_PREFIX = "https://github.com/LizardByte/Sunshine/releases/download/"
SERVICE_NAME = "DRONE_SUNSHINE"
WEB_UI_URL = "https://localhost:47990"
MAX_API_BYTES = 4 * 1024 * 1024
MAX_APPIMAGE_BYTES = 300 * 1024 * 1024
ARCHITECTURES = {"x86_64": "x86_64", "amd64": "x86_64", "aarch64": "aarch64", "arm64": "aarch64"}
_DIGEST = re.compile(r"^sha256:([0-9a-f]{64})$")
_ASSET = re.compile(r"^Sunshine_[A-Za-z0-9.+-]+_(x86_64|aarch64)\.AppImage$")
SERVICE_MARKER = "Generated by Drone Multiplayer"


def managed_root(settings: Any) -> Path:
    return Path(settings.userdata_root) / "system" / "drone-multiplayer" / "sunshine"


def managed_binary(settings: Any) -> Path:
    return managed_root(settings) / "bin" / "sunshine"


def service_path(settings: Any) -> Path:
    return Path(settings.userdata_root) / "system" / "services" / SERVICE_NAME


def service_record(settings: Any) -> Path:
    """Authenticated installation receipt (the legacy filename is retained for upgrades)."""
    return managed_root(settings).parent / "sunshine-service.sha256"


def machine_arch() -> str:
    return ARCHITECTURES.get(platform.machine().lower(), "")


class InstallError(Exception):
    """A failure with a message a person can act on."""


def select_release_asset(release: Any, arch: str) -> Dict[str, Any]:
    """The verified AppImage entry (name, url, sha256, size) for ``arch`` from a GitHub release document."""
    if not isinstance(release, dict) or not isinstance(release.get("assets"), list):
        raise InstallError("GitHub returned an unexpected release document for Sunshine.")
    for asset in release["assets"]:
        if not isinstance(asset, dict):
            continue
        name = str(asset.get("name") or "")
        match = _ASSET.match(name)
        if not match or match.group(1) != arch:
            continue
        url, size = str(asset.get("browser_download_url") or ""), asset.get("size")
        digest = _DIGEST.match(str(asset.get("digest") or "").lower())
        if not url.startswith(DOWNLOAD_PREFIX) or "\n" in url:
            raise InstallError("The Sunshine release points outside the official LizardByte repository; refusing to download it.")
        if not digest:
            raise InstallError("GitHub published no SHA-256 digest for the Sunshine download, so it cannot be verified; refusing to install it.")
        if not isinstance(size, int) or isinstance(size, bool) or not 0 < size <= MAX_APPIMAGE_BYTES:
            raise InstallError("The Sunshine download has an unexpected size; refusing to install it.")
        return {"name": name, "url": url, "sha256": digest.group(1), "size": size, "tag": m.clean_text(release.get("tag_name"), 60)}
    raise InstallError(f"The latest Sunshine release has no AppImage for {arch}.")


def _http_json(url: str) -> Any:
    request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "batocera-drone"})
    with urllib.request.urlopen(request, timeout=30, context=ssl.create_default_context()) as response:  # noqa: S310 - fixed https URL
        body = response.read(MAX_API_BYTES + 1)
    if len(body) > MAX_API_BYTES:
        raise InstallError("GitHub's release response was unexpectedly large.")
    return json.loads(body.decode("utf-8"))


def _http_download(url: str, destination: Path, expected_size: int, progress: Callable[[int], None]) -> str:
    """Stream ``url`` to ``destination``; return its SHA-256. Refuses non-HTTPS endpoints and oversized bodies."""
    request = urllib.request.Request(url, headers={"User-Agent": "batocera-drone"})
    digest, written = hashlib.sha256(), 0
    with urllib.request.urlopen(request, timeout=60, context=ssl.create_default_context()) as response:  # noqa: S310
        if not str(response.geturl()).startswith("https://"):
            raise InstallError("The Sunshine download was redirected to a non-HTTPS address; refusing it.")
        with open(destination, "wb") as handle:
            while True:
                chunk = response.read(256 * 1024)
                if not chunk:
                    break
                written += len(chunk)
                if written > expected_size:
                    raise InstallError("The Sunshine download is larger than GitHub reported; refusing it.")
                digest.update(chunk)
                handle.write(chunk)
                progress(written)
    if written != expected_size:
        raise InstallError("The Sunshine download was incomplete. Check this Drone's internet connection and try again.")
    return digest.hexdigest()


def _run(argv: List[str], *, cwd: Optional[Path] = None, timeout: float = 30.0, home: Optional[Path] = None) -> subprocess.CompletedProcess:
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LANG": "C"}
    if home is not None:
        env["HOME"] = str(home)
    return subprocess.run(argv, cwd=str(cwd) if cwd else None, capture_output=True, text=True, timeout=timeout, shell=False,
                          stdin=subprocess.DEVNULL, env=env)


class SunshineInstaller:
    """Install, start, stop and remove the Drone-managed Sunshine. One job at a time, runs off the request thread."""

    def __init__(self, settings: Any, probe: Any, *, fetch_json: Callable[[str], Any] = _http_json,
                 download: Callable[..., str] = _http_download, run: Callable[..., Any] = _run,
                 arch: Callable[[], str] = machine_arch, spawn: Optional[Callable[[Callable[[], None], str], None]] = None,
                 on_change: Optional[Callable[[], None]] = None, sleep: Callable[[float], None] = time.sleep) -> None:
        self.settings = settings
        self.probe = probe
        self._fetch_json, self._download, self._run, self._arch = fetch_json, download, run, arch
        self._spawn = spawn or (lambda fn, name: threading.Thread(target=fn, name=name, daemon=True).start())
        self._on_change = on_change or (lambda: None)
        self._sleep = sleep
        self._lock = threading.RLock()
        self._job: Dict[str, Any] = {"state": "idle", "step": "", "message": "", "percent": 0, "updated": 0.0}

    # -------------------------------------------------------------- inspection
    @property
    def root(self) -> Path:
        return managed_root(self.settings)

    def is_managed_install(self) -> bool:
        return managed_binary(self.settings).is_file() and (self.root / "app" / "AppRun").is_file()

    def installed_version(self) -> str:
        try:
            info = json.loads((self.root / "version.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return ""
        return m.clean_text(info.get("tag") if isinstance(info, dict) else "", 60)

    def job(self) -> dict:
        with self._lock:
            return {key: value for key, value in self._job.items() if key != "updated"}

    def status(self) -> dict:
        arch = self._arch()
        binary = self.probe.find_binary(("sunshine",), (str(managed_binary(self.settings)), "/usr/bin/sunshine"))
        managed = self.is_managed_install()
        installed = binary is not None or managed
        running = self.probe.process_running(("sunshine",)) if installed else False
        job = self.job()
        installing = job["state"] == "running"
        return {
            "name": "Sunshine", "purpose": "Host side of remote streaming. Guests connect with Moonlight.",
            "installed": installed, "managed": managed, "running": running,
            "version": self.installed_version() if managed else "",
            "supported": bool(arch), "architecture": platform.machine(),
            "can_install": bool(arch) and not installed and not installing,
            "can_start": installed and not running and not installing,
            "can_uninstall": managed and not installing,
            "service_installed": service_path(self.settings).is_file(),
            "install_dir": str(self.root), "web_ui": WEB_UI_URL, "job": job,
            "source": "github.com/LizardByte/Sunshine (official release, SHA-256 verified)",
            "notes": [
                "After the first start, open Sunshine's web UI on this machine and set its own username and password right away.",
                "Pairing with a guest's Moonlight uses a PIN you enter in that web UI; Drone never sees Sunshine's credentials.",
                "Uninstalling removes the program and its service but keeps Sunshine's settings and pairings.",
            ],
            **({"unsupported_reason": f"Sunshine has no build for '{platform.machine()}'."} if not arch else {}),
        }

    # -------------------------------------------------------------------- jobs
    def _set(self, state: str, step: str = "", message: str = "", percent: Optional[int] = None) -> None:
        with self._lock:
            self._job.update(state=state, step=step, message=m.clean_text(message, 300), updated=time.time())
            if percent is not None:
                self._job["percent"] = max(0, min(100, int(percent)))

    def start_install(self) -> dict:
        """Begin installing in the background. Idempotent: a running job is returned as is."""
        with self._lock:
            if self._job["state"] == "running":
                return self.status()
            arch = self._arch()
            if not arch:
                raise m.MultiplayerError("unsupported_architecture", f"Sunshine has no build for '{platform.machine()}'.", 409)
            if self.probe.find_binary(("sunshine",), (str(managed_binary(self.settings)), "/usr/bin/sunshine")):
                raise m.MultiplayerError("already_installed", "Sunshine is already installed on this machine.", 409)
            self._set("running", "checking", "Looking up the latest Sunshine release", 0)
            self._spawn(lambda: self._install(arch), "drone-sunshine-install")
        return self.status()

    def _install(self, arch: str) -> None:
        staging = self.root.parent / ".sunshine-staging"
        try:
            self._check_service_free()
            self._set("running", "checking", "Looking up the latest Sunshine release", 2)
            asset = select_release_asset(self._fetch_json(RELEASE_API), arch)
            self._remove_tree(staging)
            staging.mkdir(parents=True, mode=0o700)
            image = staging / "sunshine.AppImage"
            self._set("running", "downloading", f"Downloading {asset['name']}", 5)
            actual = self._download(asset["url"], image, asset["size"],
                                    lambda done: self._set("running", "downloading", f"Downloading {asset['name']}", 5 + int(60 * done / asset["size"])))
            self._set("running", "verifying", "Verifying the download", 66)
            if actual != asset["sha256"]:
                raise InstallError("The downloaded Sunshine file does not match GitHub's published checksum; it was discarded.")
            image.chmod(0o700)
            self._set("running", "extracting", "Unpacking Sunshine", 70)
            self._extract(image, staging)
            self._set("running", "installing", "Installing Sunshine and its service", 88)
            try:
                self._swap_in(staging / "squashfs-root", asset)
                self._write_service()
            except BaseException:
                # Install is only offered when nothing is installed, so a failure here leaves nothing worth keeping.
                self._discard_service()
                self._remove_tree(self.root)
                raise
            self._set("running", "starting", "Starting Sunshine", 95)
            started = self.start_service()
            self._on_change()
            note = "Sunshine is installed and running." if started else "Sunshine is installed but did not start; use Start Sunshine."
            self._set("succeeded", "done", note, 100)
        except InstallError as error:
            self._set("failed", "", str(error))
        except subprocess.TimeoutExpired:
            self._set("failed", "", "Unpacking Sunshine took too long and was stopped. Try again.")
        except OSError as error:
            self._set("failed", "", f"Sunshine could not be installed: {error.strerror or error.__class__.__name__}.")
        except Exception as error:  # noqa: BLE001 - surface any network/parse failure as a message, never a crash
            self._set("failed", "", f"Sunshine could not be installed: {error.__class__.__name__}. Check this Drone's internet access and try again.")
        finally:
            self._remove_tree(staging)

    def _extract(self, image: Path, staging: Path) -> None:
        # --appimage-extract needs no FUSE and writes only ./squashfs-root under ``cwd``.
        result = self._run([str(image), "--appimage-extract"], cwd=staging, timeout=300.0, home=Path(self.settings.userdata_root) / "system")
        extracted = staging / "squashfs-root"
        if getattr(result, "returncode", 1) != 0 or not (extracted / "AppRun").is_file() or not (extracted / "usr" / "bin" / "sunshine").is_file():
            raise InstallError("Sunshine could not be unpacked on this machine. The storage may block running downloaded programs.")

    def _swap_in(self, extracted: Path, asset: Dict[str, Any]) -> None:
        root = self.root
        root.mkdir(parents=True, exist_ok=True, mode=0o700)
        (root / "bin").mkdir(parents=True, exist_ok=True)
        app, previous = root / "app", root / "app.previous"
        self._remove_tree(previous)
        had_previous = app.exists()
        if had_previous:
            app.rename(previous)
        try:
            shutil.move(str(extracted), str(app))
            wrapper = managed_binary(self.settings)
            home = Path(self.settings.userdata_root) / "system"
            wrapper.write_text(f"#!/bin/sh\n# {SERVICE_MARKER} - do not edit.\n"
                               f"export HOME={shlex.quote(str(home))}\nexec {shlex.quote(str(app / 'AppRun'))} \"$@\"\n", encoding="utf-8")
            wrapper.chmod(0o755)
            (root / "version.json").write_text(json.dumps({"tag": asset["tag"], "asset": asset["name"], "sha256": asset["sha256"]}), encoding="utf-8")
            # Only a completed, verified application promotion creates signing authority.
            # Never create a key while inspecting a service or reading a receipt.
            with (root / ".service-key").open("xb") as key_file:
                os.fchmod(key_file.fileno(), 0o600)
                key_file.write(os.urandom(32))
                key_file.flush()
                os.fsync(key_file.fileno())
        except Exception:
            self._remove_tree(app)
            if had_previous:
                previous.rename(app)
            raise
        self._remove_tree(previous)

    def _check_service_free(self) -> None:
        """Refuse before anything is promoted if a service Drone did not write already owns the name."""
        target = service_path(self.settings)
        if (target.is_file() or target.is_symlink()) and not self._owns_service():
            raise InstallError(f"A different {SERVICE_NAME} service already exists on this machine; Drone will not overwrite it.")

    def _write_service(self) -> None:
        target = service_path(self.settings)
        self._check_service_free()
        if self._owns_service():
            return
        target.parent.mkdir(parents=True, exist_ok=True)
        content = self._service_text()
        key = self._service_key()
        record = service_record(self.settings)
        record.parent.mkdir(parents=True, exist_ok=True)
        # Atomic replacement prevents a restart from seeing half a receipt, and does
        # not follow a pre-existing sidecar symlink.
        temporary = None
        created = None
        try:
            # Exclusive creation also refuses a foreign file appearing after preflight.
            with target.open("x", encoding="utf-8") as script:
                created = os.fstat(script.fileno())
                script.write(content)
                os.fchmod(script.fileno(), 0o755)
                script.flush()
                os.fsync(script.fileno())
            receipt = {"version": 1, "mac": hmac.new(key, self._service_evidence(), hashlib.sha256).hexdigest()}
            with tempfile.NamedTemporaryFile(mode="w", dir=record.parent, delete=False, encoding="utf-8") as handle:
                temporary = Path(handle.name)
                json.dump(receipt, handle)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, record)
        except BaseException:
            # A failed receipt write must not strand an installed-looking service.
            # Remove only the inode this operation created, preserving any replacement.
            if created is not None:
                try:
                    current = target.lstat()
                    if (current.st_dev, current.st_ino) == (created.st_dev, created.st_ino):
                        target.unlink()
                except FileNotFoundError:
                    pass
            raise
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)

    def _service_text(self) -> str:
        binary, root = shlex.quote(str(managed_binary(self.settings))), shlex.quote(str(self.root / "app"))
        log = shlex.quote(str(Path(self.settings.userdata_root) / "system" / "logs" / "sunshine.log"))
        return (f"""#!/bin/sh
# Sunshine game-streaming host for Batocera Drone multiplayer.
# {SERVICE_MARKER} - do not edit by hand. Remove it with Uninstall in Multiplayer settings.
BIN={binary}
APP={root}
LOG={log}
PID_FILE=/tmp/drone-sunshine.pid

is_running() {{
  [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE" 2>/dev/null)" 2>/dev/null
}}

case "$1" in
  start)
    [ -x "$BIN" ] || {{ echo "[drone-sunshine] not installed" >&2; exit 1; }}
    is_running && exit 0
    mkdir -p "$(dirname "$LOG")"
    nohup "$BIN" >> "$LOG" 2>&1 &
    echo $! > "$PID_FILE"
    echo "[drone-sunshine] started (pid $(cat "$PID_FILE"))"
    ;;
  stop)
    [ -f "$PID_FILE" ] && kill "$(cat "$PID_FILE" 2>/dev/null)" 2>/dev/null
    rm -f "$PID_FILE"
    pkill -f "$APP/usr/bin/sunshine" 2>/dev/null
    echo "[drone-sunshine] stopped"
    ;;
  restart) "$0" stop; sleep 1; "$0" start ;;
  status)
    if is_running; then echo "[drone-sunshine] running"; else echo "[drone-sunshine] not running"; exit 1; fi
    ;;
  *) echo "Usage: $0 {{start|stop|restart|status}}"; exit 2 ;;
esac
exit 0
""")

    # ---------------------------------------------------------------- service
    def _batocera_services(self, action: str) -> bool:
        tool = shutil.which("batocera-services")
        if not tool:
            return False
        try:
            return self._run([tool, action, SERVICE_NAME], timeout=30.0).returncode == 0
        except (OSError, subprocess.SubprocessError):
            return False

    def _owns_service(self) -> bool:
        """Authenticate the installed script, not a public marker or reproducible checksum.

        The receipt binds both bytes and filesystem identity, so copying the service
        and its receipt onto a replacement file does not transfer ownership. This
        protects against copied metadata, not an administrator controlling Drone's
        private installation directory (Drone itself runs as root).
        """
        try:
            if not self.is_managed_install() or service_record(self.settings).is_symlink():
                return False
            with service_record(self.settings).open(encoding="utf-8") as handle:
                receipt = json.loads(handle.read(4096))
            if (not isinstance(receipt, dict) or receipt.get("version") != 1
                    or not isinstance(receipt.get("mac"), str) or not re.fullmatch(r"[0-9a-f]{64}", receipt["mac"])):
                return False
            expected = hmac.new(self._service_key(), self._service_evidence(), hashlib.sha256).hexdigest()
            return hmac.compare_digest(expected, receipt["mac"])
        except (OSError, ValueError, InstallError):
            return False

    def _service_key(self) -> bytes:
        path = self.root / ".service-key"
        info = path.lstat()
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_mode & 0o077 or info.st_size != 32:
            raise InstallError("Sunshine's private installation receipt key is invalid; Drone will not manage its service.")
        return path.read_bytes()

    def _service_evidence(self) -> bytes:
        script = service_path(self.settings)
        info = script.lstat()
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size > 64 * 1024:
            raise InstallError("Sunshine's service is not a regular Drone-owned script.")
        return json.dumps([str(script), info.st_dev, info.st_ino, hashlib.sha256(script.read_bytes()).hexdigest()],
                          separators=(",", ":")).encode("utf-8")

    def _discard_service(self) -> None:
        if self._owns_service():
            service_path(self.settings).unlink()
            service_record(self.settings).unlink(missing_ok=True)

    def _service_script(self, action: str) -> bool:
        script = service_path(self.settings)
        if not self._owns_service():
            return False
        try:
            return self._run(["sh", str(script), action], timeout=30.0).returncode == 0
        except (OSError, subprocess.SubprocessError):
            return False

    def start_service(self) -> bool:
        """Enable the service for reboots and start it now; True when a Sunshine process is up."""
        if not self._owns_service():
            if service_path(self.settings).is_file() or not self.is_managed_install():
                raise m.MultiplayerError("not_managed", "Sunshine here was not installed by Drone, so Drone does not start it. Start it from Batocera.", 409)
            self._write_service()
        self._batocera_services("enable")
        if not (self._batocera_services("start") or self._service_script("start")):
            return False
        for _ in range(10):
            if self.probe.process_running(("sunshine",)):
                break
            self._sleep(0.5)
        self._on_change()
        return self.probe.process_running(("sunshine",))

    def stop_service(self) -> None:
        if not self._owns_service():
            return
        self._batocera_services("stop")
        self._service_script("stop")

    def uninstall(self) -> dict:
        with self._lock:
            if self._job["state"] == "running":
                raise m.MultiplayerError("install_in_progress", "Sunshine is being installed right now; wait for it to finish.", 409)
            owns_service = self._owns_service()
            if not self.is_managed_install() and not owns_service:
                raise m.MultiplayerError("not_managed", "Drone did not install Sunshine on this machine, so it will not remove it.", 409)
            if owns_service:
                self.stop_service()
                self._batocera_services("disable")
                service_path(self.settings).unlink()
            if owns_service:
                service_record(self.settings).unlink(missing_ok=True)
            self._remove_tree(self.root)
            self._set("idle", "", "")
        self._on_change()
        return self.status()

    @staticmethod
    def _remove_tree(path: Path) -> None:
        if path.is_symlink():
            path.unlink()
        elif path.exists():
            shutil.rmtree(path, ignore_errors=True)
